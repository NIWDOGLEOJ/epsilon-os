//! Userspace Test Programs for the ELF Loader and Syscall Interface
//!
//! Machine code for small Ring 3 programs, assembled from the sources reproduced
//! below with `as --64` and embedded here so that exercising the loader needs no
//! userspace toolchain and no filesystem to read from. Regenerate by assembling
//! the listed source and emitting the `.text` bytes.
//!
//! Both programs are position-independent in the only way that matters here:
//! they reach their string through `lea rsi, [rip + msg]`, so they run correctly
//! at whatever address the ELF header asks to be loaded at.

/// ```asm
/// _start:
///     mov rax, 1              # SYS_WRITE
///     mov rdi, 1              # fd = stdout
///     lea rsi, [rip + msg]
