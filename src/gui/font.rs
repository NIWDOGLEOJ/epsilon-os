/// Renders the Aegis Shield logo icon (16x16)
pub fn draw_shield_icon(fb: &mut Framebuffer, x: i32, y: i32, color: Color) {
    const SHIELD_BITMAP: [u16; 16] = [
        0b0011111111111100,
        0b0111111111111110,
        0b1111100000011111,
        0b1111011111101111,
        0b1110110000110111,
        0b1110101111010111,
        0b1110101001010111,
        0b1110101001010111,
        0b0111010000101110,
        0b0111011001101110,
        0b0011101111011100,
        0b0011110110111100,
        0b0001111001111000,
        0b0000111111110000,
        0b0000011111100000,
        0b0000000110000000,
    ];

    for (row, &row_bits) in SHIELD_BITMAP.iter().enumerate() {
        let py = y + row as i32;
        for col in 0..16 {
            let px = x + col as i32;
            let bit = (row_bits >> (15 - col)) & 1;
            if bit != 0 {
                fb.draw_pixel(px, py, color);
            }
        }
    }
}

